#!/usr/bin/env node
// Writes AGENTS.md and .github/copilot-instructions.md for the tools that do not read CLAUDE.md
// (Codex, Copilot, Cursor…): CLAUDE.md followed by every .claude/rules/*.md, each with the paths it
// applies to. Claude Code itself reads CLAUDE.md + the rules directly, so these are copies, never
// sources. `--write` regenerates; without it the script only checks (pre-commit) and exits 1 if stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const normalise = text => text.replace(/\r\n/g, '\n');

function splitFrontmatter(text)
{
    const match = text.match(/^---\n([\s\S]*?)\n---\n/);

    if(!match)
    {
        return { paths: [], body: text };
    }

    const paths = [...match[1].matchAll(/^\s*-\s*"?([^"\n]+?)"?\s*$/gm)].map(m => m[1]);

    return { paths, body: text.slice(match[0].length) };
}

export function buildAgentsDoc(claudeMd, rules)
{
    const parts = [
        '<!-- GENERATED by .claude/scripts/sync-agent-docs.mjs from CLAUDE.md and .claude/rules/*.md. Do not edit: edit those and run `pnpm sync:agents`. -->',
        normalise(claudeMd).trim()
    ];

    for(const rule of rules)
    {
        const { paths, body } = splitFrontmatter(normalise(rule.text));
        const lines = body.trim().split('\n');
        const title = lines[0].startsWith('# ') ? lines.shift().slice(2) : rule.file;
        const scope = paths.length ? `_Applies to: ${paths.map(p => `\`${p}\``).join(', ')}_` : '_Applies everywhere_';

        parts.push(`## Rule: ${title}\n\n${scope}\n\n${lines.join('\n').trim()}`);
    }

    return `${parts.join('\n\n')}\n`;
}

function main()
{
    const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
    const rulesDir = join(root, '.claude', 'rules');
    const rules = readdirSync(rulesDir)
        .filter(file => file.endsWith('.md'))
        .sort()
        .map(file => ({ file, text: readFileSync(join(rulesDir, file), 'utf8') }));
    const doc = buildAgentsDoc(readFileSync(join(root, 'CLAUDE.md'), 'utf8'), rules);
    const write = process.argv.includes('--write');
    let stale = false;

    for(const target of [join(root, 'AGENTS.md'), join(root, '.github', 'copilot-instructions.md')])
    {
        let current = '';

        try
        {
            current = normalise(readFileSync(target, 'utf8'));
        }
        catch
        {
            // Missing target: written below, or reported stale in check mode.
        }

        if(current === doc)
        {
            continue;
        }

        if(write)
        {
            writeFileSync(target, doc);
            console.log(`sync-agent-docs: wrote ${target}`);
        }
        else
        {
            stale = true;
            console.error(`sync-agent-docs: ${target} is out of date with CLAUDE.md / .claude/rules. Run \`pnpm sync:agents\` and stage it.`);
        }
    }

    process.exit(stale ? 1 : 0);
}

if(process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
{
    main();
}
