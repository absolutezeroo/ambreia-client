import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildAgentsDoc } from './sync-agent-docs.mjs';

const CLAUDE = '# Vortex RPG client\n\nIntro line.\r\n\n## Commands\n\npnpm check\n';
const RULES = [
    { file: 'room.md', text: '---\npaths:\n  - "**/room/**"\n---\n\n# Room engine rules\n\nUse createObjectInternal().\n' },
    { file: 'always.md', text: '# Always\n\nNo frontmatter here.\n' }
];

test('the generated doc carries CLAUDE.md, then every rule with its scope, and a do-not-edit banner', () =>
{
    const doc = buildAgentsDoc(CLAUDE, RULES);

    assert.match(doc, /^<!-- GENERATED by \.claude\/scripts\/sync-agent-docs\.mjs/);
    assert.match(doc, /## Commands\n\npnpm check/);
    assert.match(doc, /## Rule: Room engine rules\n\n_Applies to: `\*\*\/room\/\*\*`_\n\nUse createObjectInternal\(\)\./);
    assert.match(doc, /## Rule: Always\n\n_Applies everywhere_\n\nNo frontmatter here\./);
    assert.ok(doc.indexOf('Room engine rules') > doc.indexOf('## Commands'));
    assert.ok(!doc.includes('\r'));
    assert.ok(doc.endsWith('\n'));
});
