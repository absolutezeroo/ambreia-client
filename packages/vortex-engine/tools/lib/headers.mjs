// Parses the emulator's Headers.cs and renders the client's Headers.generated.ts.
// The emulator is the source of truth for message ids:
// docs/superpowers/specs/2026-10-07-client-architecture-design.md §6.
import { existsSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const RELEASE_RE = /^AMBREIA-\d{12}$/;
const RELEASE_FILE_RE = /^AMBREIA-\d{12}\.json$/;

function releaseSide(table, key)
{
    if(!table || typeof table !== 'object') throw new Error(`release: "${key}" is not an object`);

    return new Map(Object.entries(table).map(([name, id]) =>
    {
        if(!Number.isInteger(id)) throw new Error(`release: ${key}.${name} is not an integer`);

        return [name, id];
    }));
}

/**
 * A production revision (vortex-rpg-emulator scripts/revision-new.mjs), in the client's sense: the
 * server's composers come in, its events go out.
 */
export function parseRelease(text)
{
    const json = JSON.parse(text);

    if(!RELEASE_RE.test(json.revision ?? '')) throw new Error(`release: revision "${json.revision}" is not AMBREIA-yyyyMMddHHmm`);

    return {revision: json.revision, incoming: releaseSide(json.composers, 'composers'), outgoing: releaseSide(json.events, 'events')};
}

/** The newest `AMBREIA-<12 digits>.json` of `dir` (the name sorts chronologically), or null. */
export function latestReleaseFile(dir)
{
    if(!existsSync(dir)) return null;

    const newest = readdirSync(dir).filter(name => RELEASE_FILE_RE.test(name)).sort().pop();

    return newest ? join(dir, newest) : null;
}

const CLASS_RE = /^\s*(?:internal|public)\s+static\s+class\s+(\w+)/;
const CONST_RE = /^\s*public\s+const\s+int\s+(\w+)\s*=\s*(-?\d+)\s*;/;

// What the server composes, the client receives; what the server handles, the client sends.
const DIRECTION_BY_CLASS = { MessageComposer: 'incoming', MessageEvent: 'outgoing' };

const HEADER_COMMENT = [
    '// GENERATED by packages/vortex-engine/tools/gen-headers.mjs from',
    '// vortex-rpg-emulator/Vortex.Revisions/Revision20260701/Headers.cs. Do not edit: run `pnpm gen:headers`.',
    '// Spec: docs/superpowers/specs/2026-10-07-client-architecture-design.md §6.',
    ''
].join('\n');

export function parseHeadersCs(text)
{
    const parsed = { incoming: new Map(), outgoing: new Map() };
    const nameById = { incoming: new Map(), outgoing: new Map() };
    let direction = null;

    for(const line of text.split(/\r?\n/))
    {
        const classMatch = line.match(CLASS_RE);

        if(classMatch)
        {
            direction = DIRECTION_BY_CLASS[classMatch[1]] ?? null;

            if(direction === null)
            {
                throw new Error(`Headers.cs: unexpected class ${classMatch[1]}`);
            }

            continue;
        }

        const constMatch = line.match(CONST_RE);

        if(!constMatch)
        {
            continue;
        }

        const [, name, rawId] = constMatch;

        if(direction === null)
        {
            throw new Error(`Headers.cs: constant ${name} outside MessageEvent/MessageComposer`);
        }

        const id = Number(rawId);

        // -1 marks a header the server keeps declared but does not wire.
        if(id < 0)
        {
            continue;
        }

        if(parsed[direction].has(name))
        {
            throw new Error(`Headers.cs: ${name} declared twice in ${direction}`);
        }

        const owner = nameById[direction].get(id);

        if(owner !== undefined)
        {
            throw new Error(`Headers.cs: ${name} and ${owner} share ${direction} id ${id}`);
        }

        parsed[direction].set(name, id);
        nameById[direction].set(id, name);
    }

    return parsed;
}

function renderBlock(exportName, doc, entries)
{
    const sorted = [...entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    const lines = sorted.map(([name, id]) => `    ${name}: ${id},`);

    return `/** ${doc} */\nexport const ${exportName} = {\n${lines.join('\n')}\n} as const;\n`;
}

export function renderHeadersTs(parsed, revision = 'AMBREIA-DEV')
{
    return [
        HEADER_COMMENT,
        `/** The protocol revision this client speaks, announced in ClientHello. */\nexport const REVISION = '${revision}';\n`,
        renderBlock('Incoming', 'Server to client: the emulator\'s MessageComposer constants.', parsed.incoming),
        renderBlock('Outgoing', 'Client to server: the emulator\'s MessageEvent constants.', parsed.outgoing)
    ].join('\n');
}

// Where to look for the emulator checkout, in order. A linked worktree (e.g. .claude/worktrees/x)
// has a `.git` file pointing into the main checkout's .git/worktrees/; without the second candidate
// the check would silently skip in every worktree.
export function emulatorCandidates(repoDir, dotGitText)
{
    const candidates = [join(dirname(repoDir), 'vortex-rpg-emulator')];
    const pointer = dotGitText?.match(/^gitdir:\s*(.+?)[\\/]\.git[\\/]worktrees[\\/]/m);

    if(pointer)
    {
        const main = resolve(pointer[1]);
        const candidate = join(dirname(main), 'vortex-rpg-emulator');

        if(!candidates.includes(candidate))
        {
            candidates.push(candidate);
        }
    }

    return candidates;
}

export function sameContent(a, b)
{
    return a.replace(/\r\n/g, '\n') === b.replace(/\r\n/g, '\n');
}
