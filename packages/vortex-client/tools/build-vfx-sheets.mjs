#!/usr/bin/env node
// Reads the combat effects' sheets (packages/vortex-client/spells/<folder>/<name>.json, the PixelLab
// VFX export beside its PNG) and writes their geometry for the game:
// packages/ambreia-game/src/features/combat/vfxSheets.generated.ts, keyed `<folder>/<name>`, the
// name the content's `vfx` phases use (content/skill/*.json → "sheet") and the key the bundler gives
// the image (rpg/vfx/<folder>/<name>, tools/bundle-assets.mjs). Runs before every `pnpm dev` and as
// `pnpm gen:vfx`; `--check` only tells whether the committed file is current (pre-commit). Where a sheet is pinned (body, feet) is the content's to say, not the art's.
import {existsSync, readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const SPELLS = resolve(HERE, '../spells');
export const OUT = resolve(HERE, '../../ambreia-game/src/features/combat/vfxSheets.generated.ts');

/** The geometry of one sheet from its PixelLab json. */
export function sheetEntry(key, json)
{
    const frames = Array.isArray(json.frames) ? json.frames : Object.values(json.frames);
    const first = frames[0];
    const width = first.frame.w;
    const height = first.frame.h;
    const ms = first.duration;

    if(frames.some(frame => frame.duration !== ms)) console.warn(`[vfx] ${key}: uneven frame durations, using ${ms} ms`);

    return {
        width, height, ms,
        columns: Math.max(1, Math.floor((json.meta?.size?.w ?? width) / width)),
        frames: frames.length,
        anchorX: json.meta?.anchor?.x ?? width / 2,
        anchorY: json.meta?.anchor?.y ?? height / 2
    };
}

/** Every `<folder>/<name>.json` under the spells folder. */
export function readSheets(root = SPELLS)
{
    const sheets = new Map();

    if(!existsSync(root)) return sheets;

    for(const folder of readdirSync(root, {withFileTypes: true}).filter(entry => entry.isDirectory()))
    {
        for(const file of readdirSync(join(root, folder.name)).filter(name => name.endsWith('.json')))
        {
            const key = `${folder.name}/${file.slice(0, -'.json'.length)}`;

            sheets.set(key, sheetEntry(key, JSON.parse(readFileSync(join(root, folder.name, file), 'utf8'))));
        }
    }

    return sheets;
}

export function render(sheets)
{
    const lines = [...sheets].sort(([a], [b]) => a.localeCompare(b)).map(([key, s]) =>
        `    '${key}': {width: ${s.width}, height: ${s.height}, columns: ${s.columns}, frames: ${s.frames}, ms: ${s.ms}, anchorX: ${s.anchorX}, anchorY: ${s.anchorY}}`);

    return `// Generated by packages/vortex-client/tools/build-vfx-sheets.mjs from packages/vortex-client/spells/: run \`pnpm gen:vfx\` instead of editing it.
/* eslint-disable */
/** The combat effects' sheets by \`<folder>/<name>\`, as the content names them; the image is \`rpg/vfx/<folder>/<name>\`. */
export const VFX_SHEETS = {
${lines.join(',\n')}
} as const;
`;
}

/** `--check`: true when the committed file is what the sheets render to (the pre-commit hook's question). */
export function isUpToDate(sheets = readSheets(), out = OUT)
{
    return existsSync(out) && readFileSync(out, 'utf8') === render(sheets);
}

if(process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
{
    const sheets = readSheets();

    if(process.argv.includes('--check'))
    {
        if(isUpToDate(sheets)) process.exit(0);

        console.error(`[vfx] ${OUT} is stale: run pnpm gen:vfx and commit it`);
        process.exit(1);
    }

    writeFileSync(OUT, render(sheets));
    console.log(`[vfx] ${sheets.size} sheets → ${OUT}`);
}
