// Generates src/zone/Zone.generated.ts from the emulator's schemas/zone.schema.json.
// The schema inlines every type and titles it with its C# name; each titled node is hoisted into
// $defs so json-schema-to-typescript emits one named interface per record (ZoneTile, ZoneNpc…).
//   node tools/gen-zone-types.mjs           write the file
//   node tools/gen-zone-types.mjs --check   fail when the committed file differs
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {compile} from 'json-schema-to-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = process.env.ZONE_SCHEMA
    ?? resolve(here, '../../../../vortex-rpg-emulator/schemas/zone.schema.json');
const outPath = resolve(here, '../src/zone/Zone.generated.ts');

export function hoist(root)
{
    const defs = {};

    const visit = (node) =>
    {
        if (Array.isArray(node)) return node.map(visit);
        if (node === null || typeof node !== 'object') return node;

        const {title, ...rest} = node;

        if (title && rest.$ref) return {$ref: `#/$defs/${title}`};

        const body = Object.fromEntries(Object.entries(rest).map(([k, v]) => [k, visit(v)]));

        if (!title) return body;

        defs[title] ??= {title, ...body};

        return {$ref: `#/$defs/${title}`};
    };

    const {title, ...rest} = root;
    const top = Object.fromEntries(Object.entries(rest).map(([k, v]) => [k, visit(v)]));

    return {title, ...top, $defs: defs};
}

export async function generate(schema)
{
    return compile(hoist(schema), 'ZoneDocument', {
        bannerComment: '/* GENERATED by tools/gen-zone-types.mjs from vortex-rpg-emulator/schemas/zone.schema.json. Do not edit. */',
        additionalProperties: false,
        unreachableDefinitions: true,
        style: {singleQuote: true, tabWidth: 4}
    });
}

if (process.argv[1] === fileURLToPath(import.meta.url))
{
    const ts = await generate(JSON.parse(readFileSync(schemaPath, 'utf8')));

    if (process.argv.includes('--check'))
    {
        // Git may check the file out with CRLF: only the content counts.
        if (readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n') !== ts)
        {
            console.error('Zone.generated.ts is stale: run pnpm --filter @ambreia/map-editor-core gen:types');
            process.exit(1);
        }
    }
    else
    {
        writeFileSync(outPath, ts);
        console.log(`wrote ${outPath}`);
    }
}
